function [signal_out, meta] = compensate_code_doppler( ...
        signal_in, fs, rf_carrier_hz, reference_fd_hz, ...
        reference_fdot_hz_s)
%COMPENSATE_CODE_DOPPLER Resample onto the aided transmitter-code clock.

if nargin < 5 || isempty(reference_fdot_hz_s)
    reference_fdot_hz_s = 0;
end
validateattributes(signal_in, {'numeric'}, {'vector', 'nonempty'});
validateattributes(fs, {'numeric'}, {'scalar', 'real', 'finite', 'positive'});
validateattributes(rf_carrier_hz, {'numeric'}, ...
    {'scalar', 'real', 'finite', 'positive'});
validateattributes(reference_fd_hz, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(reference_fdot_hz_s, {'numeric'}, ...
    {'scalar', 'real', 'finite'});

input_size = size(signal_in);
signal_row = signal_in(:).';
sample_axis = 0:(numel(signal_row) - 1);
t = sample_axis / double(fs);
warp_samples = double(fs) / double(rf_carrier_hz) * ...
    (double(reference_fd_hz) * t + ...
    0.5 * double(reference_fdot_hz_s) * t.^2);
transmitter_clock_axis = sample_axis + warp_samples;
signal_out = interp1(transmitter_clock_axis, signal_row, sample_axis, ...
    'linear', 0);

% Resampling the received stream also time-scales its carrier. Restore the
% aided carrier component so downstream Doppler estimates remain on the
% original physical time axis.
source_sample_axis = interp1(transmitter_clock_axis, sample_axis, ...
    sample_axis, 'linear', NaN);
valid = isfinite(source_sample_axis);
source_sample_axis(~valid) = sample_axis(~valid);
source_time = source_sample_axis / double(fs);
reference_phase_source = double(reference_fd_hz) * source_time + ...
    0.5 * double(reference_fdot_hz_s) * source_time.^2;
reference_phase_output = double(reference_fd_hz) * t + ...
    0.5 * double(reference_fdot_hz_s) * t.^2;
phase_restore_cycles = reference_phase_output - reference_phase_source;
signal_out(valid) = signal_out(valid) .* ...
    exp(1j * 2 * pi * phase_restore_cycles(valid));
signal_out(~valid) = 0;
signal_out = reshape(signal_out, input_size);
maximum_phase_restore_cycles = 0;
if any(valid)
    maximum_phase_restore_cycles = max(abs(phase_restore_cycles(valid)));
end

meta = struct( ...
    'enabled', true, ...
    'reference_fd_hz', double(reference_fd_hz), ...
    'reference_fdot_hz_s', double(reference_fdot_hz_s), ...
    'maximum_warp_samples', max(abs(warp_samples)), ...
    'carrier_phase_restored', true, ...
    'maximum_phase_restore_cycles', maximum_phase_restore_cycles, ...
    'output_zero_fraction', mean(signal_out(:) == 0));
end
